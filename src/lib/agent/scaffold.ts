export function slugify(input: string, fallback = "app") {
  const ascii = input
    .toLowerCase()
    .replace(/[^a-z0-9\u0600-\u06FF\s-]/g, "")
    .trim()
    .replace(/\s+/g, "-");
  // Persian characters are not valid npm package names → fall back.
  const clean = ascii.replace(/[^a-z0-9-]/g, "");
  return /^[a-z0-9][a-z0-9-]*$/.test(clean) ? clean : fallback;
}

export function camel(input: string) {
  return input
    .replace(/[^a-zA-Z0-9\s]/g, " ")
    .trim()
    .split(/\s+/)
    .map((w, i) => (i === 0 ? w.toLowerCase() : w.charAt(0).toUpperCase() + w.slice(1).toLowerCase()))
    .join("");
}

export function pascal(input: string) {
  const c = camel(input);
  return c.charAt(0).toUpperCase() + c.slice(1);
}

export function detectSections(input: ScaffoldInput): string[] {
  if (input.sections?.length) return input.sections.slice(0, 8);
  const haystack = `${input.projectTitle} ${input.description ?? ""}`;
  const hits = SECTION_HINTS.filter((h) => h.match.test(haystack)).flatMap((h) => h.sections);
  if (hits.length) return [...new Set(hits)].slice(0, 6);
  return DEFAULT_SECTIONS;
}

